# ============================================================================
# 反射点的形式化定义
# ============================================================================

@dataclass
class ReflectionPoint:
    """
    反射点——流程中系统停下来审视自己的行为的点

    每个反射点有：
    - 触发时机：什么时候反射
    - 反射对象：审视什么（产出/流程/认知）
    - 反射数据：用什么数据反思
    - 反射反馈：反思结果反馈到哪里
    """
    reflection_id: str
    trigger: Literal["after_loop", "match_failure", "after_stop", "periodic", "manual"]
    target: Literal["output", "process", "cognition"]
    reflection_data: dict[str, Any]       # 反射用的数据
    feedback_to: list[str]                # 反馈到哪些地方（提示词/分类体系/数据结构/Pipe衔接）
    reflection_result: Optional[dict] = None  # 反射结果（反射后填充）


